import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {InMemoryCredentialStore} from '@earendil-works/pi-ai';
import {ModelRuntime} from '@earendil-works/pi-coding-agent';
import {readPiCredential} from './dist/agent-runtimes/pi/credentials.js';
import {InitialSessionContextBuilder} from './dist/core/profiles.js';
import {savePiboCustomBasePrompt} from './dist/core/base-prompt.js';
import {SqlitePiboSessionStore} from './dist/sessions/sqlite-store.js';
import {PiboSessionRouter} from './dist/core/session-router.js';
import {PiboPluginRegistry,definePiboPlugin} from './dist/plugins/registry.js';
import {PiboReliabilityStore} from './dist/reliability/store.js';
const root=await mkdtemp('/tmp/pr993-protected-real-');
process.env.PIBO_HOME=join(root,'pibo-home');
const sessions=new SqlitePiboSessionStore(join(root,'sessions.sqlite'));
const reliability=new PiboReliabilityStore(join(root,'reliability.sqlite'));
const context=join(root,'context.md');
await writeFile(context,'The acceptance context marker is COMET-993.');
await savePiboCustomBasePrompt('Answer acceptance requests accurately and concisely.',root);
const credentials=new InMemoryCredentialStore();
const credential=await readPiCredential('openai-codex');assert.ok(credential);
await credentials.modify('openai-codex',async()=>credential);
const modelRuntime=await ModelRuntime.create({credentials,allowModelNetwork:false});
const profile='pr993-protected-real';
const registry=PiboPluginRegistry.create({plugins:[definePiboPlugin({id:'pr993.live',register(r){r.registerProfile({name:profile,create:()=>new InitialSessionContextBuilder(profile).withBuiltinTools('disabled').withAutoContextFiles(false).withToolPackages({goalControl:false}).withModel({provider:'openai-codex',id:'gpt-5.6-sol'}).addContextFile({path:context}).createSession()});}})]});
const session=sessions.create({channel:'acceptance',kind:'chat',profile,workspace:root});
let router;const usage=[];const outputs=[];
const open=enabled=>{const r=new PiboSessionRouter({cwd:root,sessionStore:sessions,reliabilityStore:reliability,pluginRegistry:registry,persistSession:true,sessionPrefixProtection:enabled,modelRuntime,thinkingLevel:'low',modelDefaults:{}});r.subscribe(e=>{if(e.type==='assistant_usage')usage.push({usage:e.usage,cacheEvidence:e.cacheEvidence});if(e.type==='assistant_message')outputs.push(e.text);});return r;};
const start=Date.now();
try{
 router=open(true);
 const first=await router.emitMessageAndWaitForReply({type:'message',piboSessionId:session.id,id:'live-first',source:'user',text:'Remember the conversation marker ORBIT-993. Reply exactly READY_COMET-993.'},90000);
 assert.equal(first.text,'READY_COMET-993');
 const before=sessions.get(session.id).runtimeBinding;assert.ok(before.metadata.piboSessionPrefix);const nativeBefore=await readFile(before.locator.value,'utf8');
 await router.disposeAll();router=undefined;
 await rm(context);await savePiboCustomBasePrompt('Changed host base: the context marker would now be WRONG.',root);
 router=open(false);
 const second=await router.emitMessageAndWaitForReply({type:'message',piboSessionId:session.id,id:'live-second',source:'user',text:'Return the original context marker and the remembered conversation marker, separated by one space. No other text.'},90000);
 assert.equal(second.text,'COMET-993 ORBIT-993');
 const after=sessions.get(session.id).runtimeBinding;
 assert.equal(after.metadata.piboSessionPrefix.capsule.digest,before.metadata.piboSessionPrefix.capsule.digest);
 assert.ok((await readFile(before.locator.value,'utf8')).startsWith(nativeBefore));
 assert.equal(usage.length,2);assert.notEqual(usage[0].cacheEvidence.runtimeGeneration,usage[1].cacheEvidence.runtimeGeneration);
 console.log(JSON.stringify({at:new Date().toISOString(),ms:Date.now()-start,piboSessionId:session.id,first,second,outputs,usage,capsule:after.metadata.piboSessionPrefix,checks:{capsuleStable:true,nativeHistoryPrefixPreserved:true,runtimeGenerationChanged:true,restoreWithRolloutOff:true,originalContextRemoved:true}},null,2));
}finally{await router?.disposeAll();reliability.close();sessions.close();}
